import { expect, test } from 'vitest'

// Vitest renders each table differently from the literal beside it, so nothing collides.
test.each([['x', 'y']])('padded $01', () => expect(1).toBe(1))
test('padded y', () => expect(2).toBe(2))
test.each([[{ 1: 'p' }, 'q']])('object first $1', () => expect(3).toBe(3))
test('object first q', () => expect(4).toBe(4))
test.each([['x', 'y']])('late index $%#', () => expect(5).toBe(5))
test('late index $0', () => expect(6).toBe(6))
test.each([['x', 'y']])('late position $%$', () => expect(7).toBe(7))
test('late position $1', () => expect(8).toBe(8))
test.each(['1.99999999999999999999'])('rounded %i', () => expect(9).toBe(9))
test('rounded 2', () => expect(10).toBe(10))
test.for([null])('null string %s', () => expect(11).toBe(11))
test('null string null', () => expect(12).toBe(12))
test.for([null])('null number %d', () => expect(13).toBe(13))
test('null number 0', () => expect(14).toBe(14))
test.for([null])('null json %j', () => expect(15).toBe(15))
test('null json null', () => expect(16).toBe(16))
test.for([null])('null object %o', () => expect(17).toBe(17))
test('null object null', () => expect(18).toBe(18))

// One edit from each above: these do collide.
test.each([['x', 'y']])('position $1', () => expect(19).toBe(19))
test('position y', () => expect(20).toBe(20))
test.each([['p', 'q']])('scalar first $1', () => expect(21).toBe(21))
test('scalar first q', () => expect(22).toBe(22))
test.each([['x', 'y']])('index $%#', () => expect(23).toBe(23))
test('index x', () => expect(24).toBe(24))
test.each([['x', 'y']])('next position $%$', () => expect(25).toBe(25))
test('next position y', () => expect(26).toBe(26))
test.each(['1.99999999999999999999'])('truncated %i', () => expect(27).toBe(27))
test('truncated 1', () => expect(28).toBe(28))
test.for([null])('missing %s', () => expect(29).toBe(29))
test('missing undefined', () => expect(30).toBe(30))
test.each([null])('each null %s', () => expect(31).toBe(31))
test('each null null', () => expect(32).toBe(32))
test.each([null])('each number %d', () => expect(33).toBe(33))
test('each number 0', () => expect(34).toBe(34))
