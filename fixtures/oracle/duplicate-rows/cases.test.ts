import { expect, test } from 'vitest'

const ONE = 1
test.each([[ONE], [1], [2]])('scalar %i', value => expect(value).toBeGreaterThan(0))
test.each([[1, 2], [1, 3]])('ignored %i', value => expect(value).toBe(1))
test.each([[1, 2], [1, 3]])('rest distinct', (value, ...rest) => expect(rest).toHaveLength(value))
test.each([[1, 2], [1, 2]])('rest repeat', (value, ...rest) => expect(rest).toHaveLength(value))
test.each([[1, 2], [1, 3]])('arguments distinct', function (value) { expect(arguments[1]).toBeGreaterThan(value) })
test.for([[3, 4], [3, 4], [3, 5]])('whole %i %i', ([left, right]) => expect(right).toBeGreaterThan(left))
test.each([{ a: 1 }, { a: 1 }, { a: 2 }])('object', ({ a }) => expect(a).toBeGreaterThan(0))
test.each([[1], [1]])('indexed %#', value => expect(value).toBe(1))
test.each([[-0], [0]])('zero', value => expect(Object.is(value, -0)).toBeTypeOf('boolean'))
test.each([[1], [1], [2], [2]])('groups %i', value => expect(value).toBeGreaterThan(0))
test.each([[1], [1], [1]])('spanning', value => expect(value).toBe(1))
test.each([[1], [1], [1], [1], [1]])('cluster', value => expect(value).toBe(1))
test.each([[1]])('other site', value => expect(value).toBe(1))
test.each([[1]])('other site', value => expect(value).toBe(1))
test.each([[1], [1]])('empty', () => {})
test.each([[1], [2]])('reassigned', value => { value = 3; expect(value).toBe(3) })
test.each([[{ a: 1 }], [{ a: 1 }]])('nested reference', value => expect(value.a).toBe(1))
test.each([{ a: 1, b: 2 }, { b: 2, a: 1 }])('property order', value => expect(Object.keys(value)).toHaveLength(2))
test.each([['1.99999999999999999999'], ['1.99999999999999999999']])('integer %i', value => expect(value).toBeTypeOf('string'))
test.each([[1], [1]])('field $01', value => expect(value).toBe(1))
test.for([null, null])('null %s', value => expect(value).toBeNull())
const fresh = () => Math.random()
test.each([[fresh()], [fresh()]])('unknown', value => expect(value).toBeTypeOf('number'))
test.for([7, 7])('primitive %i', value => expect(value).toBe(7))
test.for([[, 1], [, 1]])('holes', value => expect(value.length).toBe(2))
test.each([{ toString: 1 }, { toString: 1 }])('custom coercion', value => expect(value.toString).toBe(1))
test.each([{ ...{ a: 1 } }, { ...{ a: 1 } }])('spread object', value => expect(value.a).toBe(1))
test.for([[null, true, 's'], [null, true, 's']])('literal array', value => expect(value).toHaveLength(3))
test.each([[], []])('empty row', function () { expect(arguments.length).toBe(0) })
test.each([['\uD800'], ['\uFFFDd800']])('encoded text', value => expect(value.charCodeAt(0)).toBeGreaterThan(0))
test.each([{ '\uD800': 1 }, { '\uFFFDd800': 1 }])('encoded key', value => expect(Object.keys(value)[0].charCodeAt(0)).toBeGreaterThan(0))
test.each([['é😀'], ['é😀']])('unicode %s', value => expect(value).toHaveLength(3))
test.each([[1], [1]])('encoded title \uD800', value => expect(value).toBe(1))
test.for([ONE, 1])('whole const %i', value => expect(value).toBe(1))
test.for(['1', 1])('whole types', value => expect(typeof value).toBeTypeOf('string'))
