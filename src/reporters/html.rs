/// The page shell. Placeholders are replaced by [`render`]; nothing else in this file parses or
/// templates HTML beyond literal substring replacement, which keeps the output's shape fully
/// predictable from the placeholder list below.
const HTML_TEMPLATE: &str = include_str!("templates/report.html");

/// Renders an [`AnalysisResult`] as a single self-contained HTML file.
///
/// Unlike the terminal and JSON reporters, this reporter has no configurable fields: there is
/// no meaningful "plain" vs. "pretty" distinction for an HTML page, and no color mode to select
/// (the page's color scheme follows the reader's OS preference, with a manual toggle baked into
/// the page itself rather than chosen at generation time).
#[derive(Debug, Clone, Default)]
pub struct HtmlReporter {
    /// The exact source text of every analyzed file this run retained, keyed by the relativized
    /// path `Finding::locations` carry — see the module doc's snippet section. Empty for the
    /// default construction, which renders no snippets at all (the card keeps its pre-P1 shape)
    /// rather than an unavailability note per finding.
    sources: BTreeMap<PathBuf, String>,
}

impl HtmlReporter {
    /// Creates a reporter with no retained sources: cards render locations and titles only.
    /// Kept as a constructor (rather than requiring callers to name the unit struct directly) so
    /// it reads the same way at call sites as [`super::TerminalReporter::new`] and
    /// [`super::JsonReporter::new`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Creates the reporter with the run's retained sources, so participant bodies render as
    /// snippets sliced from the exact text the frontend parsed. `main` calls this whenever the
    /// HTML reporter is selected; the map is taken by value because the reporter outlives the
    /// analysis loop that filled it and consumes it exactly once.
    pub fn with_sources(sources: BTreeMap<PathBuf, String>) -> Self {
        Self { sources }
    }
}

impl Reporter for HtmlReporter {
    /// Renders the page and writes it; the only I/O failure possible is the writer's.
    fn write_report(&self, result: &AnalysisResult, writer: &mut dyn Write) -> Result<()> {
        let page = render(result, &self.sources).context("failed to render HTML report")?;
        writer.write_all(page.as_bytes())?;
        Ok(())
    }
}

/// Builds the complete HTML document for `result`, sourcing snippets from `sources`.
fn render(result: &AnalysisResult, sources: &BTreeMap<PathBuf, String>) -> Result<String> {
    let counts = SeverityCounts::count(&result.findings);
    let summary_line = format!(
        "{} {}, {} {}, {} {} &middot; {} tests analyzed &middot; {} files analyzed",
        counts.errors,
        pluralize(counts.errors, "error"),
        counts.warnings,
        pluralize(counts.warnings, "warning"),
        counts.off,
        pluralize(counts.off, "off finding"),
        result.tests_analyzed,
        result.files_analyzed,
    );

    let summary_line = if result.modes.suppressions_applied > 0 {
        format!(
            "{summary_line} &middot; {} suppressed by inline directive(s)",
            result.modes.suppressions_applied
        )
    } else {
        summary_line
    };
    let summary_line = if result.modes.baseline_applied {
        format!(
            "{summary_line} &middot; {} baselined, {} new",
            result.modes.baselined, result.modes.new_findings
        )
    } else {
        summary_line
    };

    // This banner is the one non-negotiable visual element in the whole page: a reader who sees
    // zero findings and stops here would wrongly conclude the codebase is duplicate-free. The
    // alert has to out-rank that assumption, not footnote it, so it sits immediately under the
    // header, before any findings or empty-state text, with a role that assistive tech announces
    // on its own.
    //
    // The causes come from `IncompleteCauses::reasons`, the same list the terminal prints, so the
    // two cannot drift -- and they had: this banner asserted "hit a limit or a parse failure" on
    // runs where no limit was hit, which reads as "the tool is too small for your repository"
    // when the truth was a number of unreadable files the reader could have acted on. The text is
    // tool-generated, but it goes through `html_escape` anyway rather than resting on that.
    let reasons = result.incomplete_causes.reasons();
    let incomplete_banner = if reasons.is_empty() {
        String::new()
    } else {
        let items = reasons
            .iter()
            .map(|reason| format!("<li>{}</li>", html_escape(reason)))
            .collect::<String>();
        format!(
            r#"<div class="incomplete-alert" role="alert"><span class="icon" aria-hidden="true">&#9888;</span><div><strong>Analysis incomplete</strong>Some tests could not be compared, so absence of a finding below is not proof that those tests are duplicate-free.<ul class="incomplete-causes">{items}</ul></div></div>"#
        )
    };

    // Rendered with the same alert treatment, and for the same reason, as the incomplete banner
    // above it: a reader who sees a short list here must not read it as a verdict on the whole
    // repository. The whole corpus was analyzed, so what is shown is accurate; what is missing is
    // everything that does not touch a changed file, which is what this says out loud.
    let changed_banner = if result.modes.changed_scope {
        let withheld = if result.modes.withheld_unchanged > 0 {
            format!(
                " {} finding(s) lying entirely within unchanged files were withheld, so this page cannot speak for the rest of the repository.",
                result.modes.withheld_unchanged
            )
        } else {
            String::new()
        };
        format!(
            r#"<div class="incomplete-alert" role="alert"><span class="icon" aria-hidden="true">&#9888;</span><div><strong>Changed-files run</strong>Only findings touching a file changed since the given revision are shown.{withheld}</div></div>"#
        )
    } else {
        String::new()
    };

    let banners = format!("{incomplete_banner}{changed_banner}");

    // P2: the per-rule totals render as filter buttons, not plain text -- discovering a rule's
    // findings used to mean scrolling to its group (or knowing to use the rule dropdown). The
    // buttons sit under the summary line, one per rule that has findings in this run, and set
    // the same rule filter the dropdown sets, so the two stay in sync by construction. Counts
    // come from the same grouping the findings body renders, so a button can never claim a
    // number the page below it does not show.
    let mut by_rule_counts: BTreeMap<Rule, usize> = BTreeMap::new();
    for finding in &result.findings {
        *by_rule_counts.entry(finding.rule).or_default() += 1;
    }
    let rule_buttons: String = by_rule_counts
        .iter()
        .map(|(id, count)| {
            format!(
                r#"<button type="button" class="rule-total" data-rule-total="{id}" aria-label="Show only {id} findings">{id} ({count})</button>"#,
                id = html_escape(id.id()),
                count = count,
            )
        })
        .collect();
    let rule_ids: Vec<&'static str> = by_rule_counts.into_keys().map(|rule| rule.id()).collect();
    let rule_options: String = rule_ids
        .iter()
        .map(|id| format!(r#"<option value="{id}">{id}</option>"#))
        .collect();

    let rule_totals = if rule_buttons.is_empty() {
        String::new()
    } else {
        format!(
            r#"<div class="rule-totals" role="group" aria-label="Findings per rule">{rule_buttons}</div>"#
        )
    };

    let findings_body = if result.findings.is_empty() {
        r#"<p class="empty-state">No findings. Every test the analyzer could compare looked unique under the rules that ran.</p>"#.to_string()
    } else {
        render_groups(result, sources)
    };

    let report_json = json_for_html(
        &serde_json::to_string(&report_data(result)).context("failed to serialize report data")?,
    );

    let replacements = [
        ("{{SUMMARY_LINE}}", summary_line.as_str()),
        ("{{INCOMPLETE_BANNER}}", banners.as_str()),
        ("{{RULE_TOTALS}}", rule_totals.as_str()),
        ("{{RULE_OPTIONS}}", rule_options.as_str()),
        ("{{FINDINGS_BODY}}", findings_body.as_str()),
        ("{{REPORT_JSON}}", report_json.as_str()),
    ];
    Ok(render_template(HTML_TEMPLATE, &replacements))
}

/// Substitutes each `{{PLACEHOLDER}}` token in `template` with its value, in a single left-to-
/// right pass over the *original* template text.
///
/// This cannot use a naive "replace, then replace again on the result" loop: a finding's title
/// is attacker-controlled and could itself contain the literal text of a later placeholder (for
/// example a title of `{{REPORT_JSON}}`). If an earlier substitution's output were rescanned for
/// remaining placeholders, that literal text — now sitting in the page at the location of an
/// earlier field — would be mistaken for the real template slot and substituted a second time,
/// corrupting the page (most likely leaving the real `<script>` slot as literal unreplaced text).
/// Scanning only the untouched suffix of the original template for the next-earliest placeholder
/// makes that impossible: substituted content is copied through verbatim and never searched.
fn render_template(template: &str, replacements: &[(&str, &str)]) -> String {
    let mut rendered = String::with_capacity(template.len());
    let mut remaining = template;
    while let Some((index, placeholder, value)) = replacements
        .iter()
        .filter_map(|(placeholder, value)| {
            remaining
                .find(placeholder)
                .map(|index| (index, *placeholder, *value))
        })
        .min_by_key(|(index, _, _)| *index)
    {
        rendered.push_str(&remaining[..index]);
        rendered.push_str(value);
        remaining = &remaining[index + placeholder.len()..];
    }
    rendered.push_str(remaining);
    rendered
}

/// Renders every finding grouped by rule, then by the file of its first location — the same
/// two-level grouping the terminal reporter uses, so a reader who knows one report can navigate
/// the other. Rule order follows [`Rule::ALL`]'s declaration order (via `BTreeMap`'s derived
/// `Ord`) rather than first-seen order, so the grouping is stable across runs regardless of the
/// order findings happen to be produced in.
fn render_groups(result: &AnalysisResult, sources: &BTreeMap<PathBuf, String>) -> String {
    let mut by_rule: BTreeMap<Rule, Vec<&Finding>> = BTreeMap::new();
    for finding in &result.findings {
        by_rule.entry(finding.rule).or_default().push(finding);
    }

    let mut out = String::new();
    for (rule, findings) in by_rule {
        out.push_str(&format!(
            r#"<section class="rule-group" data-rule-group="{}"><h2><code>{}</code></h2>"#,
            html_escape(rule.id()),
            html_escape(rule.id()),
        ));

        for (file, findings) in findings_by_file(&findings) {
            let display_path = forward_slash_path(&file);
            out.push_str(&format!(
                r#"<div class="file-group"><h3><code>{}</code></h3>"#,
                html_escape(&display_path),
            ));
            for finding in findings {
                out.push_str(&render_card(finding, sources));
            }
            out.push_str("</div>");
        }
        out.push_str("</section>");
    }
    out
}

/// Renders one finding as a self-contained `<article>` carrying the `data-rule` and
/// `data-severity` attributes the page's filter controls key off of.
fn render_card(finding: &Finding, sources: &BTreeMap<PathBuf, String>) -> String {
    let severity = severity_label(finding.severity);
    let mut locations = String::new();
    for (location, title) in finding.locations.iter().zip(&finding.titles) {
        locations.push_str(&format!(
            r#"<li><code>{}:{}:{}</code><span class="title">{}</span>{}</li>"#,
            html_escape(&forward_slash_path(&location.path)),
            location.span.start.line,
            location.span.start.column,
            html_escape(title),
            snippet_html(sources, location),
        ));
    }
    // A second badge beside the severity one, never instead of it: a baselined finding keeps the
    // severity it actually has. `data-baselined` is on the article so the page's filter controls
    // (and anyone reading the DOM) can separate accepted debt from new without re-deriving it.
    let baselined_badge = if finding.baselined {
        r#"<span class="severity-badge baselined">BASELINED</span>"#
    } else {
        ""
    };
    format!(
        r#"<article class="finding" data-rule="{}" data-severity="{}" data-baselined="{}"><div class="finding-head"><span class="severity-badge {}">{}</span>{}</div><p class="message">{}</p><ul class="locations">{}</ul></article>"#,
        html_escape(finding.rule.id()),
        severity,
        finding.baselined,
        severity,
        severity.to_uppercase(),
        baselined_badge,
        html_escape(&finding.message),
        locations,
    )
}

/// Renders one participant's source snippet for the card, from the run's retained sources.
///
/// Three outcomes, each visible on the page as itself:
///
/// - The default construction (no retained sources) renders nothing at all — the card keeps
///   exactly the shape it had before snippets existed, rather than growing an unavailability
///   note per finding. Retention is all-or-nothing per run, so "no map" means "no snippets by
///   design", which needs no apology on the page.
/// - A retained file plus an in-bounds byte span renders `<details><summary>lines a-b</summary>`
///   with the sliced text, escaped by [`html_escape`] like every other analyzed-repository
///   string — a test body is no less attacker-controlled than a title, and a snippet that
///   spans many lines is a strictly better injection vehicle than a one-line title if it were
///   ever interpolated raw.
/// - A retained run whose location cannot be sliced (file missing from the map, or the byte
///   span outside it — impossible while both come from the same read, defended anyway so a
///   future divergence fails visibly) renders an explicit note. Silence here would teach a
///   reader to trust an absence.
fn snippet_html(sources: &BTreeMap<PathBuf, String>, location: &Location) -> String {
    if sources.is_empty() {
        return String::new();
    }
    let Some(source) = sources.get(&location.path) else {
        return r#"<p class="snippet-unavailable">source not retained for this file</p>"#
            .to_string();
    };
    let start = location.span.start_byte as usize;
    let end = location.span.end_byte as usize;
    let Some(text) = source.get(start..end) else {
        return r#"<p class="snippet-unavailable">span falls outside the retained source</p>"#
            .to_string();
    };
    format!(
        r#"<details class="snippet"><summary>lines {}&#8211;{}</summary><pre><code>{}</code></pre></details>"#,
        location.span.start.line,
        location.span.end.line,
        html_escape(text),
    )
}

/// Escapes `value` for safe interpolation into HTML text or a double-quoted attribute.
///
/// Runs [`report_safe`] first so bidirectional overrides and other invisible formatting
/// characters never reach the page at all — escaping the five HTML-special characters does
/// nothing to a bidi override, which is not one of them, so skipping the sanitizer here would
/// still let a hostile title visually reorder a rendered line. The order matters: sanitize the
/// content, then escape what's left for the markup it is landing in.
fn html_escape(value: &str) -> String {
    report_safe(value)
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}

/// Escapes `value` — already-valid JSON text — so it can sit inside a `<script>` element without
/// letting attacker-controlled content close the element early.
///
/// A JSON string can legally contain the literal text `</script>`, an HTML comment opener
/// (`<!--`), or a CDATA closer (`]]>`); none of that is meaningful to a JSON parser. But the
/// browser's HTML tokenizer scans raw `<script>` content for `</script` *before* any JSON parser
/// ever runs, purely as a byte-level match, with no awareness that it is looking at a JSON
/// string. `html_escape`'s entity escaping does not help here either — entities are an HTML-text
/// concept, and this content is not HTML text, it is a raw script body. Rewriting every `<` and
/// `>` as a `\u` escape defuses `</script`, `<!--`, and `]]>` in one pass, because each of those
/// sequences depends on a literal `<` or `>` byte reaching the tokenizer; the escaped form is
/// still valid JSON (`<` decodes back to `<`), so nothing about the data is lost.
fn json_for_html(value: &str) -> String {
    let mut output = String::with_capacity(value.len());
    for character in value.chars() {
        if matches!(character, '<' | '>' | '&') {
            output.push_str(&format!("\\u{:04x}", character as u32));
        } else {
            output.push(character);
        }
    }
    output
}

/// Builds the JSON island embedded in the page, mirroring the stable JSON report schema
/// (`super::json`) closely enough that a reader who knows one recognizes the other, without
/// literally reusing its private types — the HTML reporter's JSON is a page-local convenience
/// for the client-side filter script and future tooling, not the versioned interchange format.
fn report_data(result: &AnalysisResult) -> serde_json::Value {
    serde_json::json!({
        "testsAnalyzed": result.tests_analyzed,
        "filesAnalyzed": result.files_analyzed,
        "incomplete": result.incomplete(),
        // Serialized from the struct, so a new cause appears without a second registration.
        "incompleteCauses": result.incomplete_causes,
        // Closed, tool-owned counters with no analyzed-repository text in them, so unlike every
        // string below they need no sanitization. Present for the same reason `incomplete` is:
        // a page-local reader must be able to tell a narrowed report from a clean one.
        "modes": result.modes,
        "findings": result.findings.iter().map(|finding| {
            let mut entry = serde_json::json!({
                "rule": finding.rule.id(),
                "severity": severity_label(finding.severity),
                "baselined": finding.baselined,
                "message": report_safe(&finding.message),
                "locations": finding.locations.iter().map(|location| {
                    serde_json::json!({
                        // The visible card markup gets this same treatment via `html_escape`,
                        // which runs `report_safe` on its input before entity-escaping it. The
                        // JSON island must not skip that step just because JSON-escaping already
                        // makes the *characters* safe for the `<script>` element — a bidi
                        // override or invisible character survives JSON-escaping untouched (JSON
                        // only escapes structural characters, not display-affecting ones), so a
                        // tool that reads this island's `path` and renders it verbatim would still
                        // be susceptible to the same visual-reordering attack the page's own
                        // rendering is defended against.
                        "path": report_safe_path(&location.path),
                        "line": location.span.start.line,
                        "column": location.span.start.column,
                    })
                }).collect::<Vec<_>>(),
                "titles": finding.titles.iter().map(|title| report_safe(title)).collect::<Vec<_>>(),
            });
            if !finding.registration_files.is_empty() {
                entry["registrationFiles"] = serde_json::json!(report_registration_files(finding));
            }
            entry
        }).collect::<Vec<_>>(),
    })
}

/// Pluralizes `noun` for `count`, matching the terminal reporter's summary-line convention.
fn pluralize(count: usize, noun: &str) -> String {
    if count == 1 {
        noun.to_string()
    } else {
        format!("{noun}s")
    }
}

