    /// The first location's path inside the report's JSON island -- what every hostile-path
    /// test reads back, distinct from the escaped HTML rendering of the same path.
    fn island_first_path(output: &str) -> String {
        let island = json_island(output);
        let value: serde_json::Value = serde_json::from_str(island).unwrap();
        value["findings"][0]["locations"][0]["path"]
            .as_str()
            .unwrap()
            .to_owned()
    }

    /// Render an analysis result to UTF-8 HTML text, panicking on reporter or decoding errors.
    fn render_str(result: &AnalysisResult) -> String {
        let mut buffer = Vec::new();
        HtmlReporter::new()
            .write_report(result, &mut buffer)
            .expect("writing to a Vec<u8> never fails");
        String::from_utf8(buffer).expect("HTML reporter output must be valid UTF-8")
    }

    /// The two banners that tell a reader this page does not speak for the whole repository.
    ///
    /// Both branches, and the per-finding BASELINED badge, had no coverage: every other test here
    /// renders a default `ModeSummary`, where all three are off. They are the most consequential
    /// strings this reporter emits — a changed-files run that silently looked like a full one would
    /// have someone conclude a repository is clean from a page that only ever examined a diff.
    #[test]
    fn a_scoped_or_baselined_run_says_so_on_the_page() {
        let baselined = {
            let mut result = rendered_result(vec![finding_with_title(
                Rule::DuplicateTest,
                "a.test.ts",
                "t",
            )]);
            result.modes = ModeSummary {
                baseline_applied: true,
                baselined: 3,
                new_findings: 1,
                ..ModeSummary::default()
            };
            result.findings[0].baselined = true;
            render_str(&result)
        };
        assert!(
            baselined.contains("3 baselined") && baselined.contains("1 new"),
            "a consulted baseline must show both counts: accepted debt and what is new"
        );
        assert!(
            baselined.contains("BASELINED"),
            "and the finding itself carries the badge, so the DOM separates debt from new"
        );

        let scoped = {
            let mut result = rendered_result(vec![finding_with_title(
                Rule::DuplicateTest,
                "a.test.ts",
                "t",
            )]);
            result.modes = ModeSummary {
                changed_scope: true,
                withheld_unchanged: 7,
                ..ModeSummary::default()
            };
            render_str(&result)
        };
        assert!(
            scoped.contains("Changed-files run"),
            "a scoped run must announce itself"
        );
        assert!(
            scoped.contains("7 finding(s)")
                && scoped.contains("cannot speak for the rest of the repository"),
            "and must say how many it withheld; the count is what stops the page reading as a \
             full result"
        );

        let scoped_nothing_withheld = {
            let mut result = rendered_result(vec![finding_with_title(
                Rule::DuplicateTest,
                "a.test.ts",
                "t",
            )]);
            result.modes = ModeSummary {
                changed_scope: true,
                ..ModeSummary::default()
            };
            render_str(&result)
        };
        assert!(
            scoped_nothing_withheld.contains("Changed-files run")
                && !scoped_nothing_withheld.contains("were withheld"),
            "nothing withheld means no withheld sentence, rather than one reading `0 finding(s)`"
        );
    }

