//! Self-contained, interactive HTML reporter for [`AnalysisResult`].
//!
//! The output is one HTML file with no external references — no CDN script, no remote font, no
//! remote image — because the whole point of shipping a report artifact is that it renders the
//! same way whether it is opened from a CI build, emailed, or archived for a year. A `<link>` or
//! `<script src>` pointed at a remote host would also leak the shape of the analyzed
//! repository (file paths, test titles, finding counts) to whoever controls that host, every
//! time someone opens the report. All CSS and JavaScript below are inlined for the same reason.
//!
//! The analyzed repository is untrusted input: a test title is attacker-controllable text that
//! lands verbatim in this page. Three independent defenses apply to it before it reaches the
//! generated bytes, and all three matter — dropping any one reopens a real injection:
//!
//! 1. [`html_escape`] escapes `&`, `<`, `>`, `"`, and `'` wherever a value is interpolated into
//!    HTML text or an attribute, so a title cannot introduce a tag or close an attribute.
//! 2. [`json_for_html`] additionally encodes `<` and `>` as `\u` escapes inside the JSON island,
//!    because HTML-escaping alone does not stop a JSON string's `</script`, an HTML comment
//!    opener, or a CDATA closer from being read by the browser's HTML tokenizer *before* any
//!    JSON parser ever sees the bytes — the tokenizer does not know or care that it is inside a
//!    `<script type="application/json">` element.
//! 3. [`super::shared::report_safe`] strips bidirectional-override and other invisible Unicode
//!    formatting characters before either escaper runs, because a bidi override survives
//!    HTML-escaping untouched (it is not one of the five HTML-special characters) and can
//!    visually reorder a rendered line so a finding appears to point at a different file or test
//!    than the one it actually does.
//!
//! # Source snippets come from the run's own retained sources
//!
//! [`crate::model::Finding`] carries locations (`path:line:column`) and full test titles, not
//! source snippets — the frontend never retains body text once it is fingerprinted, and a
//! reporter that *re-read* the file from disk at generation time would risk showing text that
//! no longer matches what the analyzer actually compared (the earlier recorded decision, and
//! why this report once showed no code view at all). The decision the P1 backlog row re-takes:
//! when this reporter is requested, `main` retains the exact `String` it handed the frontend
//! for every analyzed file (keyed by the same relativized path `Finding::locations` carry), so
//! a snippet sliced from it is by construction the text that was parsed and fingerprinted — no
//! staleness window, no bounds guess. Retention is conditional on this reporter being selected
//! and dies with the run, so the default pipeline's memory profile is untouched; the trade is
//! that a report run holds the corpus's source text in memory until it writes the page.
//! A location whose file is not in the map, or whose byte span falls outside it (impossible in
//! a real run, defended anyway), renders an explicit unavailability note rather than nothing —
//! a reader must be able to tell "no snippet by design" from "snippet withheld".

